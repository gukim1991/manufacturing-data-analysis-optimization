def main():
    p = Presentation(PPTX)
    assert len(NOTES) == len(p.slides), f"슬라이드 {len(p.slides)}개 vs 대본 {len(NOTES)}개 불일치"

    for i, (slide, note) in enumerate(zip(p.slides, NOTES), 1):
        notes_slide = slide.notes_slide
        tf = notes_slide.notes_text_frame
        tf.clear()
        # 첫 단락에 첫 줄 넣고, 나머지는 add_paragraph로
        lines = note.strip().split("\n")
        tf.paragraphs[0].text = lines[0]
        for line in lines[1:]:
            tf.add_paragraph().text = line
        print(f"  Slide {i:2d}: {len(note)} chars")

    p.save(PPTX)
    print(f"\n저장 완료: {PPTX}")


if __name__ == "__main__":
    main()
